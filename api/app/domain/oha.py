@dataclass(frozen=True)
class OhaRateResult:
    rental: float
    utility: float
    location_key: str | None

    @property
    def total(self):
        return self.rental + self.utility


def resolve_oha_location(location):
    if location in OHA_LOCATIONS:
        return location
    return OHA_LOCATION_ALIASES.get(location)


def get_oha_rate(location, rank, has_dependents):
    """Return monthly OHA rental and utility allowances for location/rank."""
    location_key = resolve_oha_location(location)
    loc = OHA_LOCATIONS.get(location_key, {})
    rates = loc.get("rates", {})
    pair = rates.get(rank, rates.get("E-5", (1500, 1200)))
    rental = float(pair[0] if has_dependents else pair[1])
    utility = float(loc.get("utility", 400))
    return OhaRateResult(rental=rental, utility=utility, location_key=location_key)


def list_oha_locations(clean=False):
    if clean:
        return list(OHA_LOCATION_ALIASES.keys())
    return list(OHA_LOCATIONS.keys())

